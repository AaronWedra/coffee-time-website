// Bundles db/migrations/*.sql and db/seed.sql into src/db/bundled.ts so the Worker can create and seed
// its own D1 database on first request (no wrangler needed to go live). Run by `npm run build`.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
const root = resolve(new URL('..', import.meta.url).pathname);
const dir = join(root, 'db/migrations');
const migrations = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort().map((f) => ({ name: f, sql: readFileSync(join(dir, f), 'utf8') }));
const seed = readFileSync(join(root, 'db/seed.sql'), 'utf8');
mkdirSync(join(root, 'src/db'), { recursive: true });
const out = `// GENERATED by scripts/gen-sql.mjs from db/migrations/*.sql and db/seed.sql. Do not edit.
export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 1)};
export const SEED: string = ${JSON.stringify(seed)};
`;
writeFileSync(join(root, 'src/db/bundled.ts'), out);
console.log(`bundled ${migrations.length} migrations + seed (${seed.length} chars)`);
